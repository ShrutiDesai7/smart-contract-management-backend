CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(512) NOT NULL,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS contracts (
    id UUID PRIMARY KEY,
    owner_id UUID,
    title VARCHAR(255),
    description TEXT,
    status VARCHAR(50),
    owner_name VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    contract_name VARCHAR(255),
    original_file_name VARCHAR(255),
    stored_file_name VARCHAR(255),
    content_type VARCHAR(255),
    file_size_bytes BIGINT,
    uploaded_at TIMESTAMP,
    file_path VARCHAR(1024),
    extracted_text TEXT
);

ALTER TABLE contracts ADD COLUMN IF NOT EXISTS owner_id UUID;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_contract_owner'
    ) THEN
        ALTER TABLE contracts
            ADD CONSTRAINT fk_contract_owner
            FOREIGN KEY (owner_id)
            REFERENCES users(id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS workflow_history (
    id UUID PRIMARY KEY,
    contract_id UUID NOT NULL,
    previous_status VARCHAR(50),
    new_status VARCHAR(50) NOT NULL,
    changed_by VARCHAR(255),
    comment TEXT,
    changed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_workflow_history_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
        ON DELETE CASCADE
);

ALTER TABLE workflow_history ADD COLUMN IF NOT EXISTS comment TEXT;

CREATE TABLE IF NOT EXISTS contract_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id UUID NOT NULL,
    chunk_index INTEGER,
    chunk_text TEXT NOT NULL,
    embedding BYTEA NOT NULL,
    CONSTRAINT fk_contract_chunk_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS contract_reports (
    id UUID PRIMARY KEY,
    contract_id UUID NOT NULL UNIQUE,
    summary TEXT NOT NULL,
    key_terms JSONB NOT NULL,
    risk_level VARCHAR(50) NOT NULL,
    risk_points JSONB NOT NULL,
    important_dates JSONB NOT NULL,
    obligations JSONB NOT NULL,
    generated_by VARCHAR(50) NOT NULL,
    generated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_contract_report_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_contract_status ON contracts(status);
CREATE INDEX IF NOT EXISTS idx_contract_owner_id ON contracts(owner_id);
CREATE INDEX IF NOT EXISTS idx_contract_owner_name ON contracts(owner_name);
CREATE INDEX IF NOT EXISTS idx_contract_created_at ON contracts(created_at);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
CREATE INDEX IF NOT EXISTS idx_workflow_history_contract_id ON workflow_history(contract_id);
CREATE INDEX IF NOT EXISTS idx_workflow_history_changed_at ON workflow_history(changed_at);
CREATE INDEX IF NOT EXISTS idx_contract_chunk_contract_id ON contract_chunk(contract_id);
CREATE INDEX IF NOT EXISTS idx_contract_reports_contract_id ON contract_reports(contract_id);
CREATE INDEX IF NOT EXISTS idx_contract_reports_risk_level ON contract_reports(risk_level);
