'use client'

import { useEffect, useState } from 'react'
import { getContractReport, regenerateContractReport } from '@/lib/api'
import type { ContractReport } from '@/lib/types'

type ContractReportPanelProps = {
  contractId: string
}

function formatDateTime(value: string | null): string {
  if (!value) return '-'
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '-' : date.toLocaleString()
}

function reportErrorMessage(error: unknown): string {
  return error instanceof Error ? error.message : 'Report request failed'
}

function isMissingReport(error: unknown): boolean {
  return reportErrorMessage(error).toLowerCase().includes('contract report not found')
}

function ReportList({ items, emptyText }: { items: string[]; emptyText: string }) {
  if (items.length === 0) {
    return <div className="muted">{emptyText}</div>
  }

  return (
    <ul className="report-list">
      {items.map((item) => (
        <li key={item}>{item}</li>
      ))}
    </ul>
  )
}

export function ContractReportPanel({ contractId }: ContractReportPanelProps) {
  const [report, setReport] = useState<ContractReport | null>(null)
  const [isLoading, setIsLoading] = useState(true)
  const [isGenerating, setIsGenerating] = useState(false)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false

    async function loadReport() {
      try {
        setIsLoading(true)
        setError(null)
        const result = await getContractReport(contractId)
        if (!cancelled) setReport(result)
      } catch (err) {
        if (!cancelled) {
          if (isMissingReport(err)) {
            setReport(null)
          } else {
            setError(reportErrorMessage(err))
          }
        }
      } finally {
        if (!cancelled) setIsLoading(false)
      }
    }

    loadReport()
    return () => {
      cancelled = true
    }
  }, [contractId])

  async function generateReport() {
    try {
      setIsGenerating(true)
      setError(null)
      const result = await regenerateContractReport(contractId)
      setReport(result)
    } catch (err) {
      setError(reportErrorMessage(err))
    } finally {
      setIsGenerating(false)
    }
  }

  return (
    <section className="panel">
      <div className="panel-header">
        <div>
          <h2 className="panel-title">Contract Report</h2>
          <p className="muted" style={{ margin: '4px 0 0' }}>
            Summary, key terms, risks, dates, and obligations
          </p>
        </div>
        <button className="button secondary" type="button" disabled={isGenerating} onClick={generateReport}>
          {isGenerating ? 'Generating...' : report ? 'Regenerate' : 'Generate'}
        </button>
      </div>

      {error ? <div className="error report-message">{error}</div> : null}
      {isLoading ? <div className="state muted">Loading contract report...</div> : null}

      {!isLoading && !report ? (
        <div className="state muted">No report has been generated for this contract yet.</div>
      ) : null}

      {!isLoading && report ? (
        <div className="report-body">
          <div className="report-summary">
            <div className="detail-label">Summary</div>
            <p>{report.summary}</p>
          </div>

          <div className="report-meta">
            <div>
              <div className="detail-label">Risk Level</div>
              <span className={`risk ${report.riskLevel}`}>{report.riskLevel}</span>
            </div>
            <div>
              <div className="detail-label">Generated By</div>
              <div>{report.generatedBy}</div>
            </div>
            <div>
              <div className="detail-label">Generated At</div>
              <div>{formatDateTime(report.generatedAt)}</div>
            </div>
          </div>

          <div className="report-grid">
            <div className="report-section">
              <div className="detail-label">Key Terms</div>
              <ReportList items={report.keyTerms} emptyText="No key terms found." />
            </div>
            <div className="report-section">
              <div className="detail-label">Risk Points</div>
              <ReportList items={report.riskPoints} emptyText="No risk points found." />
            </div>
            <div className="report-section">
              <div className="detail-label">Important Dates</div>
              <ReportList items={report.importantDates} emptyText="No important dates found." />
            </div>
            <div className="report-section">
              <div className="detail-label">Obligations</div>
              <ReportList items={report.obligations} emptyText="No obligations found." />
            </div>
          </div>
        </div>
      ) : null}
    </section>
  )
}
